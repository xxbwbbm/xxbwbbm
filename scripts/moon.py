"""Tonight's moon over Ho Chi Minh City -> assets/moon.svg (standard library only).

Phase from the mean synodic month (29.530588853 d) counted from the new moon of
2000-01-06 18:14 UTC. Accurate to within about a day, which is plenty for a phase drawing.
Usage: python3 scripts/moon.py [YYYY-MM-DD]   (date = the evening to draw; default: tonight in Vietnam)
"""
import base64
import datetime as dt
import math
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "moon.svg"
FONTS = ROOT / "assets" / "fonts"
SYNODIC = 29.530588853
REF_NEW = dt.datetime(2000, 1, 6, 18, 14, tzinfo=dt.timezone.utc)
ICT = dt.timezone(dt.timedelta(hours=7))
W, H = 560, 300

PHASES = [(1.84566, "New moon"), (5.53699, "Waxing crescent"), (9.22831, "First quarter"),
          (12.91963, "Waxing gibbous"), (16.61096, "Full moon"), (20.30228, "Waning gibbous"),
          (23.99361, "Last quarter"), (27.68493, "Waning crescent"), (SYNODIC, "New moon")]


def tonight(date_arg=None):
    if date_arg:
        d = dt.date.fromisoformat(date_arg)
    else:
        now = dt.datetime.now(ICT)
        d = (now - dt.timedelta(days=1)).date() if now.hour < 6 else now.date()
    return dt.datetime(d.year, d.month, d.day, 20, 0, tzinfo=ICT)   # 8 pm local


def phase(t):
    age = ((t - REF_NEW).total_seconds() / 86400) % SYNODIC
    theta = 2 * math.pi * age / SYNODIC
    lit = (1 - math.cos(theta)) / 2
    name = next(n for limit, n in PHASES if age < limit)
    to_full = (SYNODIC / 2 - age) % SYNODIC
    return age, theta, lit, name, to_full


def lit_path(theta, r):
    """Outline of the sunlit part for a waxing moon (lit on the right); mirrored later for waning."""
    rx = abs(math.cos(theta)) * r
    # right half-disc edge from top to bottom, then the terminator back to the top
    sweep_back = 0 if math.cos(theta) > 0 else 1   # crescent: terminator bows right; gibbous: bows left
    return (f"M0,{-r} A{r},{r} 0 0 1 0,{r} "
            f"A{rx:.2f},{r} 0 0 {sweep_back} 0,{-r} Z")


def font(weight, name):
    data = base64.b64encode((FONTS / name).read_bytes()).decode()
    return (f'@font-face {{ font-family: "PoppinsMoon"; font-weight: {weight}; '
            f'src: url(data:font/woff;base64,{data}) format("woff"); }}')


def build(t):
    age, theta, lit, name, to_full = phase(t)
    r = 92
    waning = age > SYNODIC / 2
    mirror = ' transform="scale(-1,1)"' if waning else ""
    path = lit_path(theta, r)
    target, days = ("Full moon", round(to_full)) if not waning else ("New moon", round(SYNODIC - age))
    if name in ("Full moon", "New moon") and days in (0, SYNODIC):
        sub = f"{name} tonight"
    elif name == "Full moon":
        sub = "Just past full"
    elif days <= 1:
        sub = f"{target} tomorrow"
    else:
        sub = f"{target} in {days} days"
    maria = ('<path d="M-52,-34 C-40,-52 -10,-50 -6,-34 C-2,-20 -22,-12 -34,-16 C-46,-20 -60,-22 -52,-34Z"/>'
             '<path d="M4,-46 C16,-56 36,-50 34,-36 C32,-26 14,-24 6,-30 C0,-34 -2,-42 4,-46Z"/>'
             '<path d="M14,-14 C30,-22 50,-6 46,14 C42,34 24,40 14,28 C6,18 2,-6 14,-14Z"/>'
             '<path d="M-38,6 C-26,-2 -8,8 -12,22 C-16,34 -34,34 -42,24 C-48,16 -46,10 -38,6Z"/>'
             '<path d="M-4,44 C6,38 20,44 16,54 C12,62 -2,62 -6,56 C-10,50 -10,46 -4,44Z"/>'
             '<circle cx="-56" cy="40" r="5"/><circle cx="44" cy="-58" r="4"/><circle cx="-14" cy="-64" r="3.5"/>')
    date_txt = f"{t.strftime('%b')} {t.day}, {t.year}"
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
<!-- Regenerated by scripts/moon.py (workflow now-playing.yml). Moon age {age:.2f} d, {lit * 100:.1f}% lit. -->
<defs>
  <radialGradient id="halo"><stop offset=".55" stop-color="#5b7bf0" stop-opacity=".22"/><stop offset="1" stop-color="#5b7bf0" stop-opacity="0"/></radialGradient>
  <radialGradient id="litg" cx=".38" cy=".35" r=".8"><stop offset="0" stop-color="#ffffff"/><stop offset=".7" stop-color="#dfe6f8"/><stop offset="1" stop-color="#aeb9d8"/></radialGradient>
  <filter id="soft" x="-20%" y="-20%" width="140%" height="140%"><feGaussianBlur stdDeviation="2.6"/></filter>
  <clipPath id="litc"><path d="{path}"{mirror}/></clipPath>
</defs>
<style>
  {font(400, "Poppins-Regular-subset.woff")}
  {font(500, "Poppins-Medium-subset.woff")}
  text {{ font-family: "PoppinsMoon", "Poppins", "Segoe UI", Helvetica, Arial, sans-serif; }}
</style>
<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="10" fill="#04082c"/>
<g transform="translate(140,150)">
  <circle r="{r * 1.5}" fill="url(#halo)" opacity="{.35 + .65 * lit:.2f}"/>
  <circle r="{r}" fill="#0e1442"/>
  <g fill="#0a0f36" opacity=".7" filter="url(#soft)">{maria}</g>
  <g clip-path="url(#litc)">
    <circle r="{r}" fill="url(#litg)"/>
    <g fill="#8f9cc2" opacity=".32" filter="url(#soft)">{maria}</g>
  </g>
  <circle r="{r}" fill="none" stroke="#5b7bf0" stroke-opacity=".25"/>
</g>
<text x="268" y="94" fill="#8a92c4" font-size="24">Tonight over Saigon</text>
<text x="268" y="142" fill="#eaf1ff" font-size="31" font-weight="500">{name}</text>
<text x="268" y="184" fill="#cbcddb" font-size="24">{round(lit * 100)}% lit</text>
<text x="268" y="220" fill="#cbcddb" font-size="24">{sub}</text>
<text x="268" y="262" fill="#6a72a8" font-size="20">{date_txt}</text>
</svg>
'''


def main(argv):
    t = tonight(argv[0] if argv else None)
    OUT.write_text(build(t), encoding="utf-8")
    age, _, lit, name, _ = phase(t)
    print(f"{t.date()}: {name}, {lit * 100:.0f}% lit (age {age:.1f} d)")


if __name__ == "__main__":
    main(sys.argv[1:])
