"""Selected projects: one card per entry in scripts/projects.json -> assets/project-*.svg,
plus the README block between the PROJECTS markers (one row of cards, each linking to the project).

Live numbers (commit count, last update, stars) come from the GitHub REST API; set GITHUB_TOKEN to
avoid rate limits (the workflow does). Standard library only.
Usage: python3 scripts/projects.py [--offline]
"""
import base64
import datetime as dt
import hashlib
import html
import json
import os
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ROOT / "assets" / "fonts"
W, H = 420, 190


def api(path):
    req = urllib.request.Request(f"https://api.github.com/{path}", headers={
        "Accept": "application/vnd.github+json", "User-Agent": "profile-readme",
        **({"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}"} if os.environ.get("GITHUB_TOKEN") else {})})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r), r.headers


def live_stats(repo):
    info, _ = api(f"repos/{repo}")
    _, headers = api(f"repos/{repo}/commits?per_page=1&sha={info['default_branch']}")
    m = re.search(r'[?&]page=(\d+)>; rel="last"', headers.get("Link", ""))
    commits = int(m.group(1)) if m else 1
    pushed = dt.datetime.fromisoformat(info["pushed_at"].replace("Z", "+00:00"))
    return {"commits": commits, "stars": info["stargazers_count"], "updated": pushed.strftime("%b %Y")}


def wrap(text, width):
    lines, cur = [], ""
    for word in text.split():
        if len(cur) + len(word) + (1 if cur else 0) > width:
            lines.append(cur)
            cur = word
        else:
            cur = f"{cur} {word}" if cur else word
    if cur:
        lines.append(cur)
    return lines


def font(weight, name):
    data = base64.b64encode((FONTS / name).read_bytes()).decode()
    return (f'@font-face {{ font-family: "PoppinsProj"; font-weight: {weight}; '
            f'src: url(data:font/woff;base64,{data}) format("woff"); }}')


def card(p, stats):
    """Compact card sized like the GitHub stats cards so three fit on one row."""
    e = html.escape
    desc = wrap(p["description"], 40)
    if len(desc) > 2:                                   # keep two lines, mark the cut
        desc = [desc[0], desc[1].rstrip(".,;:") + "…"]
    meta = p["kind"]
    if stats:
        meta += f', {stats["commits"]} commits'
        if stats["stars"]:
            meta += f', {stats["stars"]} stars'
    desc_svg = "".join(f'<text x="26" y="{84 + i * 24}" class="desc">{e(line)}</text>' for i, line in enumerate(desc))
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
<!-- Generated by scripts/projects.py from scripts/projects.json -->
<style>
  {font(400, "Poppins-Regular-subset.woff")}
  {font(500, "Poppins-Medium-subset.woff")}
  text {{ font-family: "PoppinsProj", "Poppins", "Segoe UI", Helvetica, Arial, sans-serif; }}
  .title {{ font-size: 25px; font-weight: 500; fill: #eaf1ff; }}
  .desc {{ font-size: 17px; fill: #cbcddb; }}
  .tech {{ font-size: 16px; font-weight: 500; fill: #9fb0f5; }}
  .meta {{ font-size: 14px; fill: #6a72a8; }}
</style>
<rect x=".5" y=".5" width="{W - 1}" height="{H - 1}" rx="4.5" fill="#04082c"/>
<text x="26" y="48" class="title">{e(p["title"])}</text>
{desc_svg}
<text x="26" y="{H - 44}" class="tech">{e(", ".join(p["stack"]))}</text>
<text x="26" y="{H - 20}" class="meta">{e(meta)}</text>
</svg>
'''


def slug(repo):
    return re.sub(r"[^a-z0-9]+", "-", repo.split("/")[-1].lower()).strip("-")


def main(argv):
    offline = "--offline" in argv
    projects = json.loads((ROOT / "scripts" / "projects.json").read_text(encoding="utf-8"))
    cells = []
    for p in projects:
        stats = None
        if not offline:
            try:
                stats = live_stats(p["repo"])
            except Exception as exc:   # keep building the card even if the API is unavailable
                print(f"  ! {p['repo']}: {exc}")
        stats = stats or p.get("fallback")
        svg = card(p, stats)
        name = f"project-{slug(p['repo'])}.svg"
        (ROOT / "assets" / name).write_text(svg, encoding="utf-8")
        ver = hashlib.sha1(svg.encode()).hexdigest()[:10]
        cells.append(f'<a href="{p["url"]}"><img width="32%" src="./assets/{name}?v={ver}" '
                     f'alt="{html.escape(p["title"])}: {html.escape(p["description"])}" /></a>')
        print(f"{p['title']}: {stats}")

    rows = '<p align="center">\n  ' + "\n  ".join(cells) + "\n</p>"
    readme = ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- PROJECTS:START -->", "<!-- PROJECTS:END -->"
    if start in text and end in text:
        a, b = text.index(start), text.index(end) + len(end)
        readme.write_text(text[:a] + f"{start}\n{rows}\n{end}" + text[b:], encoding="utf-8")
    else:
        print("README markers not found; cards written, README untouched")


if __name__ == "__main__":
    main(sys.argv[1:])
